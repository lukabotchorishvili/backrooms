import {
  ANOMALY_CATEGORIES,
  AnomalyDefinition,
  AnomalyEffect,
  DifficultyConfig,
  DoorDefinition,
  EndingDefinition,
  PROP_TYPES,
  PropPlacement,
  Rect,
  RoomDefinition,
  SURFACE_MATERIAL_IDS,
  StageDefinition,
  rectContains,
} from '../models';
import { ContentRegistry } from './content-registry';

export interface ValidationIssue {
  readonly level: 'error' | 'warning';
  readonly path: string;
  readonly message: string;
}

export interface ValidationOptions {
  /** Effect types with a registered engine handler (validated when provided). */
  readonly knownEffectTypes?: readonly string[];
}

/** Ids of props generated by the engine for doors (nameplates + gaze targets). */
export function doorDerivedPropIds(door: DoorDefinition): string[] {
  const ids = [`door-${door.id}`];
  if (door.sign) ids.push(`sign-${door.id}`);
  return ids;
}

export function allStageProps(stage: StageDefinition): Map<string, { prop: PropPlacement; room: RoomDefinition }> {
  const map = new Map<string, { prop: PropPlacement; room: RoomDefinition }>();
  for (const room of stage.rooms) {
    for (const prop of room.props) map.set(prop.id, { prop, room });
  }
  return map;
}

function rectValid(r: Rect): boolean {
  return r.x1 > r.x0 && r.z1 > r.z0;
}

function overlaps(a: Rect, b: Rect): boolean {
  return a.x0 < b.x1 - 0.01 && a.x1 > b.x0 + 0.01 && a.z0 < b.z1 - 0.01 && a.z1 > b.z0 + 0.01;
}

/** Does the door lie on the boundary of the room, fully within that wall span? */
export function doorOnRoomWall(door: DoorDefinition, room: RoomDefinition): boolean {
  const b = room.bounds;
  const half = door.width / 2;
  if (door.axis === 'x') {
    if (Math.abs(door.at - b.x0) > 0.01 && Math.abs(door.at - b.x1) > 0.01) return false;
    return door.center - half >= b.z0 + 0.05 && door.center + half <= b.z1 - 0.05;
  }
  if (Math.abs(door.at - b.z0) > 0.01 && Math.abs(door.at - b.z1) > 0.01) return false;
  return door.center - half >= b.x0 + 0.05 && door.center + half <= b.x1 - 0.05;
}

function inRoom(room: RoomDefinition, x: number, z: number, margin: number): boolean {
  if (rectContains(room.bounds, x, z, margin)) return true;
  return (room.extraBounds ?? []).some((r) => rectContains(r, x, z, margin));
}

/** Breadth-first search over door connections. */
export function reachableRooms(stage: StageDefinition, fromRoomId: string): Set<string> {
  const seen = new Set<string>([fromRoomId]);
  const queue = [fromRoomId];
  while (queue.length) {
    const current = queue.shift()!;
    for (const door of stage.doors) {
      if (door.initialState === 'locked') continue;
      const [a, b] = door.rooms;
      const next = a === current ? b : b === current ? a : null;
      if (next && !seen.has(next)) {
        seen.add(next);
        queue.push(next);
      }
    }
  }
  return seen;
}

const SOUND_EFFECT_TYPES = new Set(['sound', 'announcement', 'footstep-echo']);

export function validateStage(
  stage: StageDefinition,
  registry: ContentRegistry,
  options: ValidationOptions = {},
): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const error = (path: string, message: string) => issues.push({ level: 'error', path, message });
  const warn = (path: string, message: string) => issues.push({ level: 'warning', path, message });
  const p = `stage:${stage.id}`;

  // ---- rooms
  const roomIds = new Set<string>();
  for (const room of stage.rooms) {
    const rp = `${p}.rooms.${room.id}`;
    if (roomIds.has(room.id)) error(rp, 'duplicate room id');
    roomIds.add(room.id);
    if (!rectValid(room.bounds)) error(rp, 'invalid bounds (x1 must be > x0 and z1 > z0)');
    (room.extraBounds ?? []).forEach((r, i) => !rectValid(r) && error(`${rp}.extraBounds[${i}]`, 'invalid rect'));
    if (room.height < 2.4) error(rp, `height ${room.height} is too low for the player`);
    for (const s of [room.surfaces.floor, room.surfaces.walls, room.surfaces.ceiling]) {
      if (!(SURFACE_MATERIAL_IDS as readonly string[]).includes(s)) error(rp, `unknown surface material "${s}"`);
    }
    const lightIds = new Set<string>();
    for (const light of room.lights) {
      if (lightIds.has(light.id)) error(`${rp}.lights.${light.id}`, 'duplicate light id');
      lightIds.add(light.id);
      if (!inRoom(room, light.position[0], light.position[2], 0.2)) warn(`${rp}.lights.${light.id}`, 'light outside room bounds');
    }
    if (room.lights.length > 4) warn(rp, 'more than 4 lights per room may exceed the per-material light budget');
  }
  for (let i = 0; i < stage.rooms.length; i++) {
    for (let j = i + 1; j < stage.rooms.length; j++) {
      if (overlaps(stage.rooms[i].bounds, stage.rooms[j].bounds)) {
        error(`${p}.rooms`, `rooms "${stage.rooms[i].id}" and "${stage.rooms[j].id}" overlap`);
      }
    }
  }

  // ---- props
  const propIds = new Set<string>();
  for (const room of stage.rooms) {
    for (const prop of room.props) {
      const pp = `${p}.rooms.${room.id}.props.${prop.id}`;
      if (propIds.has(prop.id)) error(pp, 'duplicate prop id');
      propIds.add(prop.id);
      if (!(PROP_TYPES as readonly string[]).includes(prop.type)) error(pp, `unknown prop type "${prop.type}"`);
      if (!inRoom(room, prop.position[0], prop.position[2], 0.6)) {
        error(pp, `position (${prop.position[0]}, ${prop.position[2]}) is outside room "${room.id}"`);
      }
      const interaction = prop.interaction;
      if (interaction) {
        if (!interaction.name) error(pp, 'interaction requires a name');
        if (interaction.kind === 'inspect' && !interaction.note) warn(pp, 'inspectable prop without a note');
        if (interaction.kind === 'pickup' && !interaction.flag) error(pp, 'pickup requires a flag');
      }
    }
  }

  // ---- doors
  const doorIds = new Set<string>();
  for (const door of stage.doors) {
    const dp = `${p}.doors.${door.id}`;
    if (doorIds.has(door.id)) error(dp, 'duplicate door id');
    doorIds.add(door.id);
    for (const derived of doorDerivedPropIds(door)) {
      if (propIds.has(derived)) error(dp, `derived prop id "${derived}" collides with a prop`);
      propIds.add(derived);
    }
    for (const roomId of door.rooms) {
      const room = stage.rooms.find((r) => r.id === roomId);
      if (!room) {
        error(dp, `unknown room "${roomId}"`);
        continue;
      }
      if (!doorOnRoomWall(door, room)) error(dp, `door does not lie on a wall of "${roomId}"`);
      if (door.height > room.height - 0.2) error(dp, `door taller than room "${roomId}"`);
    }
    if (door.width < 0.8) warn(dp, 'door narrower than 0.8 m may be hard to pass');
  }

  // ---- connectivity: every room must be reachable from the hub
  if (!roomIds.has(stage.hubRoomId)) error(`${p}.hubRoomId`, `unknown hub room "${stage.hubRoomId}"`);
  else {
    const reachable = reachableRooms(stage, stage.hubRoomId);
    for (const id of roomIds) if (!reachable.has(id)) error(`${p}.doors`, `room "${id}" is unreachable from the hub`);
  }

  // ---- spawn / terminal / elevator / cameras
  const [sx, , sz] = stage.spawn.position;
  if (!stage.rooms.some((r) => inRoom(r, sx, sz, 0))) error(`${p}.spawn`, 'spawn is not inside any room');
  const hub = stage.rooms.find((r) => r.id === stage.hubRoomId);
  const terminal = hub?.props.find((pr) => pr.id === stage.terminalPropId);
  if (!terminal) error(`${p}.terminalPropId`, `terminal prop "${stage.terminalPropId}" not found in hub`);
  else if (terminal.interaction?.kind !== 'terminal') error(`${p}.terminalPropId`, 'terminal prop needs interaction kind "terminal"');
  const lobby = stage.rooms.find((r) => r.id === stage.elevator.lobbyRoomId);
  if (!lobby) error(`${p}.elevator`, `unknown lobby room "${stage.elevator.lobbyRoomId}"`);
  else {
    const car = stage.elevator.car;
    const inExtra = (lobby.extraBounds ?? []).some(
      (r) => car.x0 >= r.x0 - 0.01 && car.x1 <= r.x1 + 0.01 && car.z0 >= r.z0 - 0.01 && car.z1 <= r.z1 + 0.01,
    );
    if (!inExtra) error(`${p}.elevator.car`, 'elevator car must be covered by the lobby extraBounds');
  }
  for (const id of [stage.elevator.callPanelPropId, stage.elevator.carPanelPropId, stage.elevator.indicatorPropId]) {
    if (!propIds.has(id)) error(`${p}.elevator`, `unknown prop "${id}"`);
  }
  const cameraIds = new Set<string>();
  for (const cam of stage.securityCameras) {
    if (cameraIds.has(cam.id)) error(`${p}.securityCameras.${cam.id}`, 'duplicate camera id');
    cameraIds.add(cam.id);
    if (!roomIds.has(cam.roomId)) error(`${p}.securityCameras.${cam.id}`, `unknown room "${cam.roomId}"`);
  }

  // ---- content references
  if (stage.requiredReports < 1) error(`${p}.requiredReports`, 'must be at least 1');
  for (const id of stage.anomalyIds) {
    const def = registry.anomalies.get(id);
    if (!def) {
      error(`${p}.anomalyIds`, `unknown anomaly "${id}"`);
      continue;
    }
    issues.push(...validateAnomaly(def, stage, registry, propIds, cameraIds, options));
  }
  if (new Set(stage.anomalyIds).size < stage.requiredReports + 3) {
    error(`${p}.anomalyIds`, `pool of ${stage.anomalyIds.length} is too small for ${stage.requiredReports} required reports`);
  }
  if (stage.fallbackAnomalyIds.length === 0) error(`${p}.fallbackAnomalyIds`, 'at least one fallback anomaly is required');
  for (const id of stage.fallbackAnomalyIds) {
    const def = registry.anomalies.get(id);
    if (!def || !stage.anomalyIds.includes(id)) {
      error(`${p}.fallbackAnomalyIds`, `fallback "${id}" must be in the stage anomaly pool`);
      continue;
    }
    if (def.trigger.type !== 'immediate' || def.conditions?.requiresVisited || def.conditions?.requiresDoorState) {
      error(`${p}.fallbackAnomalyIds`, `fallback "${id}" must be immediate with no visit/door requirement`);
    }
  }
  for (const id of stage.decoyIds) {
    const decoy = registry.decoys.get(id);
    if (!decoy) error(`${p}.decoyIds`, `unknown decoy "${id}"`);
    else {
      if (!roomIds.has(decoy.roomId)) error(`decoy:${id}`, `unknown room "${decoy.roomId}"`);
      decoy.effects.forEach((e, i) => validateEffect(e, `decoy:${id}.effects[${i}]`, stage, registry, propIds, cameraIds, options, error));
    }
  }
  for (const id of stage.endingIds) {
    const ending = registry.endings.get(id);
    if (!ending) error(`${p}.endingIds`, `unknown ending "${id}"`);
    else issues.push(...validateEnding(ending));
  }
  if (!stage.endingIds.some((id) => registry.endings.get(id)?.trigger === 'elevator-standard')) {
    error(`${p}.endingIds`, 'at least one ending must use the standard elevator trigger');
  }
  for (const id of stage.behaviorResponseIds) {
    if (!registry.behaviorResponses.has(id)) error(`${p}.behaviorResponseIds`, `unknown behaviour response "${id}"`);
  }
  for (const music of [stage.music.ambient, stage.music.tension]) {
    if (!registry.sounds.has(music)) error(`${p}.music`, `unknown sound "${music}"`);
  }
  for (const room of stage.rooms) {
    for (const s of room.ambience.soundscape) {
      if (!registry.sounds.has(s)) error(`${p}.rooms.${room.id}.ambience`, `unknown sound "${s}"`);
    }
  }

  // ---- every difficulty must be completable
  for (const diff of registry.difficulties.all()) {
    const allowed = stage.anomalyIds.filter((id) => {
      const def = registry.anomalies.get(id);
      return def && diff.anomalies.allowedRatings.includes(def.difficulty) && diff.anomalies.ratingWeights[def.difficulty] > 0;
    });
    if (allowed.length < stage.requiredReports + 2) {
      error(`${p}`, `difficulty "${diff.id}" only allows ${allowed.length} anomalies (needs ${stage.requiredReports + 2})`);
    }
  }
  return issues;
}

function validateEffect(
  effect: AnomalyEffect,
  path: string,
  stage: StageDefinition,
  registry: ContentRegistry,
  propIds: Set<string>,
  cameraIds: Set<string>,
  options: ValidationOptions,
  error: (path: string, message: string) => void,
): void {
  if (options.knownEffectTypes && !options.knownEffectTypes.includes(effect.type)) {
    error(path, `no engine handler registered for effect type "${effect.type}"`);
  }
  const roomIds = new Set(stage.rooms.map((r) => r.id));
  const doorIds = new Set(stage.doors.map((d) => d.id));
  const needProp = (id: string | undefined) => {
    if (id && !propIds.has(id)) error(path, `unknown prop "${id}"`);
  };
  switch (effect.type) {
    case 'transform-prop':
    case 'hide-prop':
    case 'show-prop':
    case 'swap-variant':
    case 'set-text':
    case 'clock':
      needProp(effect.propId);
      break;
    case 'light-color':
    case 'light-pattern': {
      const room = stage.rooms.find((r) => r.id === effect.roomId);
      if (!room) error(path, `unknown room "${effect.roomId}"`);
      for (const id of effect.lightIds ?? []) {
        if (room && !room.lights.some((l) => l.id === id)) error(path, `unknown light "${id}" in "${effect.roomId}"`);
      }
      if (effect.type === 'light-pattern' && !/^[01]+$/.test(effect.pattern)) error(path, 'pattern must be 0/1 characters');
      break;
    }
    case 'door-state':
      if (!doorIds.has(effect.doorId)) error(path, `unknown door "${effect.doorId}"`);
      break;
    case 'room-revert':
      if (!roomIds.has(effect.roomId)) error(path, `unknown room "${effect.roomId}"`);
      effect.doorIds.forEach((d) => !doorIds.has(d) && error(path, `unknown door "${d}"`));
      break;
    case 'ceiling-height':
    case 'room-silence':
    case 'footstep-echo':
      if (!roomIds.has(effect.roomId)) error(path, `unknown room "${effect.roomId}"`);
      break;
    case 'sound':
      if (!registry.sounds.has(effect.soundId)) error(path, `unknown sound "${effect.soundId}"`);
      if (effect.radius <= 0) error(path, 'sound radius must be positive');
      break;
    case 'announcement':
      if (!effect.text.trim()) error(path, 'announcement text is empty');
      break;
    case 'security-feed':
      if (!cameraIds.has(effect.cameraId)) error(path, `unknown camera "${effect.cameraId}"`);
      break;
  }
}

export function validateAnomaly(
  def: AnomalyDefinition,
  stage: StageDefinition,
  registry: ContentRegistry,
  propIds: Set<string> = new Set(
    [...allStageProps(stage).keys()].concat(stage.doors.flatMap((d) => doorDerivedPropIds(d))),
  ),
  cameraIds: Set<string> = new Set(stage.securityCameras.map((c) => c.id)),
  options: ValidationOptions = {},
): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const path = `anomaly:${def.id}`;
  const error = (pth: string, message: string) => issues.push({ level: 'error', path: pth, message });
  const roomIds = new Set(stage.rooms.map((r) => r.id));

  if (!def.id.trim()) error(path, 'empty id');
  if (!(ANOMALY_CATEGORIES as readonly string[]).includes(def.category)) error(path, `unknown category "${def.category}"`);
  (def.acceptedCategories ?? []).forEach((c) => {
    if (!(ANOMALY_CATEGORIES as readonly string[]).includes(c)) error(path, `unknown accepted category "${c}"`);
  });
  if (def.difficulty < 1 || def.difficulty > 5) error(path, 'difficulty must be 1..5');
  if (!roomIds.has(def.roomId)) error(path, `unknown room "${def.roomId}"`);
  (def.alternateRoomIds ?? []).forEach((r) => !roomIds.has(r) && error(path, `unknown alternate room "${r}"`));
  if (def.targetPropId && !propIds.has(def.targetPropId)) error(path, `unknown target prop "${def.targetPropId}"`);
  if (def.effects.length === 0) error(path, 'anomaly needs at least one effect');
  def.effects.forEach((e, i) => validateEffect(e, `${path}.effects[${i}]`, stage, registry, propIds, cameraIds, options, error));
  if (!def.clue.observation.trim()) error(path, 'clue observation text is required (fairness rule)');
  switch (def.clue.mode) {
    case 'inspect':
    case 'sight':
      if (!def.clue.targetPropId) error(path, `clue mode "${def.clue.mode}" requires targetPropId`);
      else if (!propIds.has(def.clue.targetPropId)) error(path, `unknown clue target "${def.clue.targetPropId}"`);
      else if (def.clue.mode === 'inspect') {
        const entry = allStageProps(stage).get(def.clue.targetPropId);
        if (entry && !entry.prop.interaction) error(path, `clue target "${def.clue.targetPropId}" is not interactable`);
      }
      break;
    case 'feed':
      if (!def.clue.cameraId || !cameraIds.has(def.clue.cameraId)) error(path, 'feed clue requires a valid cameraId');
      break;
    case 'hearing':
      if (!def.effects.some((e) => SOUND_EFFECT_TYPES.has(e.type))) error(path, 'hearing clue requires a sound-producing effect');
      break;
    case 'presence':
      break;
  }
  if (def.cooldownSec < 0) error(path, 'cooldown must be >= 0');
  if ((def.weight ?? 1) < 0) error(path, 'weight must be >= 0');
  for (const id of [...(def.conflictsWith ?? []), ...(def.dependsOn ?? [])]) {
    if (!registry.anomalies.has(id)) error(path, `references unknown anomaly "${id}"`);
  }
  if (def.conditions?.requiresDoorState && !stage.doors.some((d) => d.id === def.conditions!.requiresDoorState!.doorId)) {
    error(path, `unknown door in requiresDoorState`);
  }
  return issues;
}

export function validateDifficulty(config: DifficultyConfig): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const path = `difficulty:${config.id}`;
  const error = (message: string) => issues.push({ level: 'error', path, message });
  const a = config.anomalies;
  if (a.maxSimultaneous < 1) error('maxSimultaneous must be >= 1');
  if (a.initialSelections < 0 || a.initialSelections > a.maxSimultaneous) error('initialSelections must be 0..maxSimultaneous');
  if (a.evaluationIntervalSec <= 0) error('evaluationIntervalSec must be > 0');
  if (a.allowedRatings.length === 0) error('allowedRatings is empty');
  if (!a.allowedRatings.some((r) => a.ratingWeights[r] > 0)) error('no allowed rating has a positive weight');
  if (a.subtlety < 0 || a.subtlety > 1) error('subtlety must be 0..1');
  if (a.maxPerRoom < 1) error('maxPerRoom must be >= 1');
  if (config.attention.falseReportPenalty <= 0) error('falseReportPenalty must be > 0');
  if (config.attention.correctReportRelief < 0) error('correctReportRelief must be >= 0');
  if (config.shiftDurationMin <= 0) error('shiftDurationMin must be > 0');
  return issues;
}

export function validateEnding(ending: EndingDefinition): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const path = `ending:${ending.id}`;
  if (ending.conditions.length === 0) {
    issues.push({ level: 'warning', path, message: 'ending has no conditions (always eligible)' });
  }
  if (!ending.conditions.some((c) => c.type === 'investigation-complete')) {
    issues.push({ level: 'error', path, message: 'every ending must require investigation-complete' });
  }
  if (ending.epilogue.lines.length === 0) issues.push({ level: 'error', path, message: 'epilogue needs at least one line' });
  if (ending.sequence.fadeSec <= 0) issues.push({ level: 'error', path, message: 'fadeSec must be > 0' });
  return issues;
}

/** Validates everything registered. Used at boot (dev) and in unit tests. */
export function validateRegistry(registry: ContentRegistry, options: ValidationOptions = {}): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  for (const d of registry.difficulties.all()) issues.push(...validateDifficulty(d));
  for (const stage of registry.stages.all()) issues.push(...validateStage(stage, registry, options));
  return issues;
}

export function formatIssues(issues: readonly ValidationIssue[]): string {
  return issues.map((i) => `[${i.level.toUpperCase()}] ${i.path}: ${i.message}`).join('\n');
}
